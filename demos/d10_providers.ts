/**
 * D10 · 换提供方 Demo
 *
 * 终端工具 = 模型想在「命令行」里跑一句话（Claude Code 里常叫 Bash）
 * 读文件工具 = 模型想打开某个文件看内容（Claude Code 里常叫 Read）
 *
 * 这两个工具都不自己碰你的电脑。
 */

function 终端工具(
  模型想做的事: string,
  在哪台电脑跑: '我的电脑' | '云端电脑',
  笼子: '只能看不能改' | '只准改这个项目' | '完全不管',
  笼子有没有漏: '关严了' | '有漏洞',
) {
  console.log('模型说:', 模型想做的事)
  console.log('  ① 终端工具：只记下这件事，自己不去按回车')
  console.log('  ② 沙箱：给命令套笼子 →', 笼子, '/', 笼子有没有漏)
  console.log('  ③ 真正按回车的地方 →', 在哪台电脑跑)
}

console.log('第一次：在我电脑上跑，笼子关严')
终端工具('看看这个文件夹里有哪些文件', '我的电脑', '只准改这个项目', '关严了')

console.log('')
console.log('第二次：还是同一个终端工具，只换了跑的地方')
终端工具('看看这个文件夹里有哪些文件', '云端电脑', '只能看不能改', '有漏洞')
